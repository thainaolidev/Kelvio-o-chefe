export function translateMessage(message, language) {
  if (language !== 'en') return message;
  const packCount = message.match(/^O pack de (\d+) marmitas tem de incluir exatamente \1 unidades\.$/);
  if (packCount) return `The pack of ${packCount[1]} meals must contain exactly ${packCount[1]} units.`;
  if (message === 'Nos packs maiores, pelo menos cinco marmitas têm de ser do mesmo sabor.') return 'For larger packs, at least five meals must be the same flavour.';
  return validationMessages.get(message) ?? message;
}
