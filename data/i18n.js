export function translateMarkup(html) {
  const dictionary = new Map(translations);
  const text = (value) => {
    const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
    return `${match[1]}${dictionary.get(match[2]) ?? match[2]}${match[3]}`;
  };
  html = html.replace(/>([^<>]*)</g, (match, value) => `>${text(value)}<`);
  return html.replace(/<[^>]+>/g, (tag) => tag.replace(/\b(aria-label|alt|placeholder|title)="([^"]*)"/g, (attribute, key, value) => `${key}="${dictionary.get(value) ?? value}"`));
}

